        private static MissionDefinition PlaceholderMission(string missionId, int arenaIndex, string arenaId, string chapterId,
            int difficulty)
        {
            return Mission(
                missionId,
                string.Empty,
                string.Empty,
                arenaIndex,
                arenaId,
                new[] { "weapon.impulse" },
                System.Array.Empty<string>(),
                0,
                difficulty: difficulty,
                chapterId: chapterId,
                enemyLoadoutId: "enemy.training.direct",
                difficultyProfileId: difficulty == 0 ? "difficulty.easy" : difficulty == 1 ? "difficulty.normal" : "difficulty.hard");
        }

        private static MissionDefinition Mission(
            string missionId,
            string title,
            string description,
            int arenaIndex,
            string arenaId,
            string[] allowedWeaponIds,
            string[] tutorialStepIds,
            int softCurrency,
            string unlockWeaponId = "",
            int difficulty = 0,
            string chapterId = "",
            string enemyLoadoutId = "",
            string difficultyProfileId = "",
            int commanderExperience = 0,
            int blueprints = 0,
            string blueprintWeaponId = "")
        {
            var missionTextKey = difficulty switch
            {
                0 => "campaign.mission.easy",
                2 => "campaign.mission.hard",
                _ => "campaign.mission.medium"
            };
            var titleKey = missionTextKey;
            var descriptionKey = missionTextKey;
            title = Game.Core.Localization.GameText.Localized(titleKey, string.Empty);
            description = Game.Core.Localization.GameText.Localized(descriptionKey, string.Empty);
            return MissionDefinition.CreateRuntime(
                missionId,
                title,
                description,
                arenaIndex,
                allowedWeaponIds,
                tutorialStepIds,
                new MissionRewardDefinition(
                    softCurrency,
                    unlockWeaponId,
                    commanderExperience,
                    blueprints,
                    blueprintWeaponId),
                difficulty,
                chapterId,
                arenaId: arenaId,
                enemyLoadoutId: enemyLoadoutId,
                difficultyProfileId: difficultyProfileId,
                displayNameKey: titleKey,
                descriptionKey: descriptionKey);
        }
