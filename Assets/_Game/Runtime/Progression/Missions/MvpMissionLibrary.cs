                difficultyProfileId: "difficulty.hard");
        }

        private static MissionDefinition Mission(
            string missionId,
            string title,
            string description,
            int arenaIndex,
            string arenaId,
            string[] allowedWeaponIds,
            string[] tutorialStepIds,
            int softCurrency,
            string unlockWeaponId = "",
            int difficulty = 0,
            string chapterId = "",
            string enemyLoadoutId = "",
            string difficultyProfileId = "",
            int commanderExperience = 0,
            int blueprints = 0,
            string blueprintWeaponId = "",
            MissionObjectiveKind objectiveKind = MissionObjectiveKind.None,
            int objectiveThreshold = 0)
        {
            // A map-only QA placeholder intentionally has no player-facing
            // copy. Released missions obtain copy from the localization table.
            title = Game.Core.Localization.GameText.Localized("missionText." + missionId + ".title", string.Empty);
            description = Game.Core.Localization.GameText.Localized("missionText." + missionId + ".description", string.Empty);
            return MissionDefinition.CreateRuntime(
                missionId,
                title,
                description,
                arenaIndex,
                allowedWeaponIds,
                tutorialStepIds,
                new MissionRewardDefinition(
                    softCurrency,
                    unlockWeaponId,
                    commanderExperience,
                    blueprints,
                    blueprintWeaponId),
                difficulty,
                chapterId,
                arenaId: arenaId,
                enemyLoadoutId: enemyLoadoutId,
                difficultyProfileId: difficultyProfileId,
                objectiveKind: objectiveKind,
                objectiveThreshold: objectiveThreshold);
        }
